    fun mainActivity(project: ProjectConfig, entryHtml: String): String {
        val w = project.web
        val immersiveBlock = if (w.immersive) """
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
            window.insetsController?.apply {
                hide(android.view.WindowInsets.Type.statusBars() or android.view.WindowInsets.Type.navigationBars())
                systemBarsBehavior = android.view.WindowInsetsController.BEHAVIOR_SHOW_TRANSIENT_BARS_BY_SWIPE
            }
        } else {
            @Suppress("DEPRECATION")
            window.decorView.systemUiVisibility = window.decorView.systemUiVisibility or
                (View.SYSTEM_UI_FLAG_IMMERSIVE_STICKY or View.SYSTEM_UI_FLAG_FULLSCREEN or View.SYSTEM_UI_FLAG_HIDE_NAVIGATION)
        }
""".trimIndent() else ""

        val fullscreenBlock = if (w.fullscreen) """
        window.setFlags(
            WindowManager.LayoutParams.FLAG_FULLSCREEN,
            WindowManager.LayoutParams.FLAG_FULLSCREEN
        )
""".trimIndent() else ""

        val keepScreenOn = if (w.keepScreenOn) "        window.addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON)" else ""

        val orientationCode = when (project.orientation) {
            Orientation.AUTO -> ""
            Orientation.PORTRAIT -> "        requestedOrientation = ActivityInfo.SCREEN_ORIENTATION_PORTRAIT"
            Orientation.LANDSCAPE -> "        requestedOrientation = ActivityInfo.SCREEN_ORIENTATION_LANDSCAPE"
        }

        return """
package ${project.packageName}

import android.annotation.SuppressLint
import android.os.Build
import android.os.Bundle
import android.view.View
import android.view.WindowManager
import android.webkit.WebChromeClient
import android.webkit.WebResourceRequest
