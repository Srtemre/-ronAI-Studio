    fun manifest(project: ProjectConfig): String {
        val p = project.permissions
        val permLines = buildList {
            if (p.internet) add("    <uses-permission android:name=\"android.permission.INTERNET\" />")
            if (p.networkState) add("    <uses-permission android:name=\"android.permission.ACCESS_NETWORK_STATE\" />")
            if (p.storage) add("    <uses-permission android:name=\"android.permission.READ_EXTERNAL_STORAGE\" android:maxSdkVersion=\"32\" />")
            if (p.camera) add("    <uses-permission android:name=\"android.permission.CAMERA\" />")
            if (p.microphone) add("    <uses-permission android:name=\"android.permission.RECORD_AUDIO\" />")
            if (p.location) add("    <uses-permission android:name=\"android.permission.ACCESS_FINE_LOCATION\" />")
            if (p.notifications && project.advanced.targetSdk >= 33) add("    <uses-permission android:name=\"android.permission.POST_NOTIFICATIONS\" />")
            if (p.vibrate) add("    <uses-permission android:name=\"android.permission.VIBRATE\" />")
        }.joinToString("\n")

        val orientationAttr = when (project.orientation) {
            Orientation.AUTO -> "unspecified"
            Orientation.PORTRAIT -> "portrait"
            Orientation.LANDSCAPE -> "landscape"
        }
        return """
<?xml version="1.0" encoding="utf-8"?>
<manifest xmlns:android="http://schemas.android.com/apk/res/android">

$permLines

    <application
        android:name=".App"
        android:label="@string/app_name"
        android:icon="@mipmap/ic_launcher"
        android:roundIcon="@mipmap/ic_launcher_round"
        android:theme="@style/Theme.App"
        android:usesCleartextTraffic="${project.web.mixedContent}"
        android:allowBackup="true">

        <activity
            android:name=".MainActivity"
            android:exported="true"
            android:screenOrientation="$orientationAttr"
            android:configChanges="orientation|screenSize|keyboardHidden|uiMode">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity>
    </application>
</manifest>
""".trimIndent()
    }

    private fun escapeXml(text: String): String =
        text.replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace("\"", "&quot;")
            .replace("'", "&apos;")
}
