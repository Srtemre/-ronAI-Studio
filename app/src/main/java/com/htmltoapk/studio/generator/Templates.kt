class MainActivity : ComponentActivity() {

    private lateinit var webView: WebView

    @SuppressLint("SetJavaScriptEnabled")
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
$orientationCode
${if (w.edgeToEdge) "        WindowCompat.setDecorFitsSystemWindows(window, false)" else ""}
$fullscreenBlock
$immersiveBlock
$keepScreenOn
        webView = WebView(this).apply {
            setContentView(this)
            configure()
            loadUrl("file:///android_asset/$entryHtml")
        }
        onBackPressedDispatcher.addCallback(this, object : OnBackPressedCallback(true) {
            override fun handleOnBackPressed() {
                if (this@MainActivity::webView.isInitialized && webView.canGoBack()) webView.goBack()
                else { isEnabled = false; onBackPressedDispatcher.onBackPressed() }
            }
        })
    }

    private fun WebView.configure() {
        settings.apply {
            ${webSettingsLines(w)}
        }
        webViewClient = object : WebViewClient() {
            override fun shouldOverrideUrlLoading(view: WebView, request: WebResourceRequest): Boolean {
                view.loadUrl(request.url.toString())
                return true
            }
        }
        webChromeClient = WebChromeClient()
    }
}
""".trimIndent()
    }

    private fun webSettingsLines(w: WebViewConfig): String {
        val b = StringBuilder()
        b.appendLine("javaScriptEnabled = ${w.javaScript}")
        b.appendLine("domStorageEnabled = ${w.domStorage}")
        b.appendLine("allowMixedContent = WebSettings.MIXED_CONTENT_${if (w.mixedContent) "ALWAYS_ALLOW" else "NEVER_ALLOW"}")
        b.appendLine("cacheMode = ${cacheModeConstant(w.cacheMode)}")
        when (w.userAgentMode) {
            UserAgentMode.DEFAULT -> {}
            UserAgentMode.DESKTOP -> b.appendLine("userAgentString = \"Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36\"")
            UserAgentMode.CUSTOM -> if (w.customUserAgent.isNotBlank()) b.appendLine("userAgentString = \"${w.customUserAgent.replace("\"", "\\\"")}\"")
        }
        b.appendLine("displayZoomControls = ${w.zoom}")
        b.appendLine("builtInZoomControls = ${w.zoom}")
        b.appendLine("mediaPlaybackRequiresUserGesture = ${!w.mediaPlayback}")
        b.appendLine("allowFileAccess = ${w.fileAccess}")
        b.appendLine("allowContentAccess = ${w.fileAccess}")
        b.appendLine("loadsImagesAutomatically = ${w.loadRemote}")
        b.appendLine("blockNetworkLoads = ${!w.loadRemote}")
        return b.toString().trimEnd()
    }

    private fun cacheModeConstant(mode: CacheMode): String = when (mode) {
        CacheMode.DEFAULT -> "WebSettings.LOAD_DEFAULT"
        CacheMode.NO_CACHE -> "WebSettings.LOAD_NO_CACHE"
        CacheMode.CACHE_ELSE_NETWORK -> "WebSettings.LOAD_CACHE_ELSE_NETWORK"
        CacheMode.NETWORK_ELSE_CACHE -> "WebSettings.LOAD_CACHE_NORMAL"
        CacheMode.CACHE_ONLY -> "WebSettings.LOAD_CACHE_ONLY"
    }

